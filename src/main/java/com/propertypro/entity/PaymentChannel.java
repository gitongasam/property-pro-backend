package com.propertypro.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.OffsetDateTime;
import java.util.UUID;

/**
 * An organisation's own Paybill / Till, a bank Paybill (e.g. KCB 522522) or a bank account.
 * Daraja secrets and bank account numbers are encrypted.
 */
@Getter
@Setter
@Entity
@Table(name = "payment_channels")
public class PaymentChannel extends TenantRow {

    public enum Type { MPESA_PAYBILL, MPESA_TILL, BANK_ACCOUNT, BANK_PAYBILL }

    public enum Environment { SANDBOX, PRODUCTION }

    @Column(name = "property_id")
    private UUID propertyId;

    @Enumerated(EnumType.STRING)
    @Column(name = "channel_type", nullable = false)
    private Type channelType;

    @Column(nullable = false)
    private String name;

    private String shortcode;

    @Column(name = "bank_name")
    private String bankName;

    /** BANK_PAYBILL / BANK_ACCOUNT: a row in banks (KCB, EQUITY, ..., OTHER). */
    @Column(name = "bank_code")
    private String bankCode;

    @Column(name = "bank_account_no_enc")
    private byte[] bankAccountNoEnc;

    @Column(name = "consumer_key_enc")
    private byte[] consumerKeyEnc;

    @Column(name = "consumer_secret_enc")
    private byte[] consumerSecretEnc;

    @Column(name = "passkey_enc")
    private byte[] passkeyEnc;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private Environment environment = Environment.SANDBOX;

    /** Secret part of this channel's callback URLs; generated by the database. */
    @Column(name = "webhook_token", insertable = false, updatable = false)
    private String webhookToken;

    @Column(name = "urls_registered_at")
    private OffsetDateTime urlsRegisteredAt;

    /** When the first real payment arrived through this channel. */
    @Column(name = "verified_at")
    private OffsetDateTime verifiedAt;

    @Column(nullable = false)
    private boolean active = true;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private OffsetDateTime createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private OffsetDateTime updatedAt;
}
